import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import test from 'node:test';
import { createProxy, trialRequests } from '../lib/proxy.mjs';

const MODEL = 'meta-llama/llama-3.1-8b-instruct';
const NOW = Date.parse('2026-10-09T12:00:00Z');
const ENV = {
  OPENROUTER_API_KEY: 'test-secret-never-return', OPENROUTER_MODEL: MODEL,
  OPENROUTER_PROVIDER: 'deepinfra/fp8', TRIAL_ENABLED: 'true',
  TRIAL_BUDGET_USD: '5', TRIAL_EXPIRES_AT: '2026-10-09T13:00:00Z',
};
const KEY = { limit: 5, limit_remaining: 4.5, limit_reset: null,
  include_byok_in_limit: true, is_management_key: false, is_provisioning_key: false };
const requests = trialRequests(MODEL);
const rawCompletion = '{ "choices": [{"message":{"role":"assistant","content":"ANSWER: 18"},"finish_reason":"stop"}], "usage":{"total_tokens":20} }';
const request = (body = requests[0], headers = {}) => new Request('https://example.test/api/chat/completions', {
  method: 'POST', headers: { 'Content-Type': 'application/json', ...headers }, body: typeof body === 'string' ? body : JSON.stringify(body),
});
function fixture({ env = {}, key = {}, completion = rawCompletion, status = 200, fetchImpl, ...options } = {}) {
  const calls = [];
  const fakeFetch = async (url, init) => {
    calls.push({ url, init });
    if (url.endsWith('/key')) return Response.json({ data: { ...KEY, ...key } });
    return new Response(completion, { status });
  };
  return { calls, handle: createProxy({ env: { ...ENV, ...env }, now: () => NOW,
    fetchImpl: fetchImpl || fakeFetch, ...options }) };
}

test('allowlist matches all 72 bodies generated by the real contract', () => {
  const script = `import json, sys
sys.path.insert(0, 'scripts')
import rehearse
seen = []
def http(url, body):
    seen.append(json.loads(body))
    return 200, json.dumps({'choices': [{'message': {'content': 'ANSWER: 0'}}]}).encode()
rehearse.run_rehearsal(rehearse.load_claim('calibration/claim-gsm8k.json'), '${MODEL}', 0, http)
print(json.dumps(seen))`;
  const actual = JSON.parse(execFileSync('python3', ['-c', script], { cwd: new URL('../', import.meta.url), encoding: 'utf8' }));
  const ordered = list => list.map(item => JSON.stringify(item, ['model', 'messages', 'role', 'content', 'temperature', 'top_p', 'max_tokens', 'seed'])).sort();
  assert.equal(actual.length, 72);
  assert.deepEqual(ordered(requests), ordered(actual));
});

test('health is free, works without configuration, and never reveals secrets', async () => {
  let calls = 0;
  const handle = createProxy({ env: {}, fetchImpl: async () => { calls++; throw new Error('unexpected fetch'); } });
  const health = await handle(new Request('https://example.test/api/chat/completions'));
  assert.equal(health.status, 200);
  assert.deepEqual(await health.json(), { service: 'impeach-openrouter', enabled: false, status: 'trial_disabled' });
  const enabled = fixture();
  const ready = await enabled.handle(new Request('https://example.test/api/chat/completions'));
  const body = await ready.json();
  assert.equal(body.allowed_requests, 72);
  assert.equal(body.status, 'configured');
  assert.equal(body.policy_sha256.length, 64);
  assert.equal(JSON.stringify(body).includes(ENV.OPENROUTER_API_KEY), false);
  assert.equal(calls + enabled.calls.length, 0);
});

