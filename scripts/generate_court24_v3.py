#!/usr/bin/env python3
"""Generate and check a disclosed v2 arithmetic copy, entirely offline.

Run from any directory. --check compares deterministic generated bytes without
writing. The replay uses OLD v2 responses for NEW prefixed requests: it tests
local contract plumbing, not the subject's performance on the new text.
"""
import argparse
import ast
from collections import Counter
from copy import deepcopy
from fractions import Fraction
import hashlib
import json
from pathlib import Path
import socket
import sys
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "test"))
import population as pop
import scenarios as scenarios
from drivers import StubDriver

PREFIX = "An independent arithmetic exercise states: "
SEED = 240526
DATASET = "court24-v3"
MODEL = "meta-llama/llama-3.1-8b-instruct"
PROVIDER = {"only": ["deepinfra/fp8"], "allow_fallbacks": False,
            "require_parameters": True,
            "max_price": {"prompt": 0.05, "completion": 0.10, "request": 0}}
DISCLOSURE = (
    "This is an explicitly disclosed arithmetic copy of court24-v2. The exact "
    "prefix 'An independent arithmetic exercise states: ' is added once to "
    "every original, rewrite and control; the word independent is prompt text, "
    "not a claim of an independent benchmark. Answers, formulas and classes "
    "are unchanged. Public deterministic salts and different text hashes permit "
    "a separate claim without reusing spent content. They establish neither "
    "secrecy, worldwide novelty nor absence from model training."
)


def packed(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode()


def sha(data):
    return hashlib.sha256(data).hexdigest()


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def exact_formula(expression):
    """Small exact arithmetic evaluator; division cannot silently truncate."""
    def visit(node):
        if isinstance(node, ast.Constant) and type(node.value) is int:
            return Fraction(node.value)
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            return -visit(node.operand)
        if isinstance(node, ast.BinOp):
            a, b = visit(node.left), visit(node.right)
            if isinstance(node.op, ast.Add):
                return a + b
            if isinstance(node.op, ast.Sub):
                return a - b
            if isinstance(node.op, ast.Mult):
                return a * b
            if isinstance(node.op, (ast.Div, ast.FloorDiv)):
                answer = a / b
                if isinstance(node.op, ast.FloorDiv):
                    assert answer.denominator == 1, "nonexact floor division"
                return answer
        raise ValueError("unsupported arithmetic node")
    result = visit(ast.parse(expression, mode="eval").body)
    assert result.denominator == 1, "noninteger reference answer"
    return str(result.numerator)


def generate():
    originals = {p: (ROOT / p).read_bytes() for p in
                 ("contracts/impeach.py", "build/impeach.py")}

    def read(path):
        raw = (ROOT / path).read_bytes()
        originals[path] = raw
        return json.loads(raw)

    base_claim = read("calibration/claim-court24-v2.json")
    base_items_doc = read(base_claim["items"])
    base_items = base_items_doc["items"]
    base_audit = read("calibration/court24-v2-audit.json")
    assert len(base_items) == len(base_audit["items"]) == 24
    claim = deepcopy(base_claim)
    claim.update(subject=MODEL + "@deepinfra-fp8/court24-v3/2026-10-11",
                 endpoint="https://impeach.vercel.app/api/live-v3/chat/completions",
                 score_milli=1000, items="calibration/court24-v3.items.json",
                 rewrites="examples/court24-v3/rewrites")
    claim["extras"]["trial_window_s"] = 21600
    assert claim["extras"]["reveal_window_s"] == 3600
    assert claim["decode_params"] == {
        "temperature": 0, "top_p": 1, "max_tokens": 512, "seed": 7, "model": MODEL}
    terms = deepcopy(claim)
    for name in ("subject", "endpoint", "items", "rewrites"):
        terms[name] = base_claim[name]
    terms["extras"]["trial_window_s"] = base_claim["extras"]["trial_window_s"]
    assert terms == base_claim, "unexpected change to frozen terms"

    items_doc = deepcopy(base_items_doc)
    items_doc.update(dataset=DATASET,
                     description="Disclosed prefixed copy of court24-v2 arithmetic for a separate court claim.",
                     note=DISCLOSURE,
                     construction={
                         "seed": SEED, "source_items": base_claim["items"],
                         "source_items_sha256": sha(originals[base_claim["items"]]),
                         "prefix": PREFIX,
                         "salt_derivation": 'First 32 hexadecimal characters of SHA256(UTF-8("impeach/court24-v3|seed=240526|item=NN")); NN is the zero-padded item index.',
                         "answers_formulas_classes": "Unchanged from court24-v2."})
    items = items_doc["items"]
    for index, item in enumerate(items):
        assert PREFIX not in item["prompt"]
        item.update(prompt=PREFIX + item["prompt"],
                    salt=sha(f"impeach/{DATASET}|seed={SEED}|item={index:02d}".encode())[:32],
                    source=f"synthetic/{DATASET}/{index:02d}")
        assert item["answer"] == base_items[index]["answer"]

    outputs = {claim["items"]: packed(items_doc),
               "calibration/claim-court24-v3.json": packed(claim)}
    base_rewrites, rewrites, controls = {}, {}, []
    for folder in ("rewrites", "controls"):
        paths = sorted((ROOT / "examples/court24-v2" / folder).glob("*.json"))
        assert len(paths) == (24 if folder == "rewrites" else 4)
        for path in paths:
            old = read(path.relative_to(ROOT).as_posix())
            env = deepcopy(old)
            assert PREFIX not in env["prompt"]
            env["prompt"] = PREFIX + env["prompt"]
            assert dict(env, prompt=old["prompt"]) == old
            target = f"examples/{DATASET}/{folder}/{path.name}"
            outputs[target] = packed(env)
            if folder == "rewrites":
                index = env["item_index"]
                assert index not in rewrites
                base_rewrites[index], rewrites[index] = old, env
            else:
                controls.append(env)
    assert sorted(rewrites) == list(range(24))
    assert Counter(e["class"] for e in rewrites.values()) == {
        "paraphrase": 5, "numeral_substitution": 5, "entity_rename": 5,
        "unit_change": 5, "format_shift": 4}

    prior_commitments, prior_content, prior_salts = set(), set(), set()
    prior_claims = []
    for path in sorted((ROOT / "calibration").glob("claim-*.json")):
        if path.name == "claim-court24-v3.json":
            continue
        old_claim = read(path.relative_to(ROOT).as_posix())
        prior_claims.append(path.relative_to(ROOT).as_posix())
        old_doc = read(old_claim["items"])
        old_items = old_doc["items"] if isinstance(old_doc, dict) else old_doc
        for item in old_items:
            prior_commitments.add(pop.tool.item_commitment(item["prompt"], item["answer"], item["salt"]))
            prior_content.add(pop.tool.content_hash(item["prompt"]))
            prior_salts.add(item["salt"])
        for folder in (Path(old_claim["rewrites"]), Path(old_claim["rewrites"]).parent / "controls"):
            for path in sorted((ROOT / folder).glob("*.json")):
                env = read(path.relative_to(ROOT).as_posix())
                prior_content.add(pop.tool.content_hash(env["prompt"]))
    assert set(prior_claims) >= {
        "calibration/claim-gsm8k.json", "calibration/claim-court24-v2.json",
        "calibration/claim-court24-v2-scripted.json"}
    new_commitments = set(scenarios.hashes_of(items))
    new_content = {pop.tool.content_hash(i["prompt"]) for i in items}
    rewrite_content = {pop.tool.content_hash(e["prompt"]) for e in rewrites.values()}
    control_content = {pop.tool.content_hash(e["prompt"]) for e in controls}
    assert len(new_commitments) == len(new_content) == len(rewrite_content) == 24
    assert len({i["salt"] for i in items}) == 24
    assert not new_commitments & prior_commitments
    assert not (new_content | rewrite_content | control_content) & prior_content
    assert not {i["salt"] for i in items} & prior_salts

    world = pop.World({"items": items, "rewrites": rewrites, "controls": controls})
    driver = StubDriver(world)
    module = driver.module
    assert claim["scoring_rule"] == module.NUMERIC_LINE_RULE
    item_audit = []
    for index, item in enumerate(items):
        env, old_audit = rewrites[index], base_audit["items"][index]
        assert old_audit["item_index"] == index
        assert exact_formula(old_audit["original_formula"]) == item["answer"]
        assert exact_formula(old_audit["rewrite_formula"]) == env["answer"]
        assert exact_formula(env["derivation"]) == env["answer"]
        assert env["class"] == old_audit["class"]
        assert not pop.tool.validate_envelope(env, item)
        assert not module.precheck_rewrite(env["class"], item["prompt"], item["answer"], env["prompt"], env["answer"])
        assert module.item_commitment(item["prompt"], item["answer"], item["salt"]) in new_commitments
        for prompt in (item["prompt"], env["prompt"]):
            assert 0 < len(prompt) <= module.MAX_ITEM_CHARS
            assert module.content_hash(prompt) == pop.tool.content_hash(prompt)
            assert module.recall_eligible(prompt, 400)
        same_answer = item["answer"] == env["answer"]
        assert same_answer == (env["class"] != "numeral_substitution")
        item_audit.append({
            "item_index": index, "class": env["class"],
            "original_formula": old_audit["original_formula"], "original_answer": item["answer"],
            "rewrite_formula": old_audit["rewrite_formula"], "rewrite_answer": env["answer"],
            "same_answer": same_answer, "formula_copy_preserved": True,
            "source_invariant_review": old_audit["invariant_review"],
            "item_commitment": module.item_commitment(item["prompt"], item["answer"], item["salt"]),
            "content_hash": module.content_hash(item["prompt"]),
            "rewrite_content_hash": module.content_hash(env["prompt"]),
            "rewrite_hash": module.rewrite_hash(env["class"], env["prompt"], env["answer"]),
            "precheck_error": "", "cli_envelope_errors": [],
            "original_prompt_chars": len(item["prompt"]), "rewrite_prompt_chars": len(env["prompt"]),
        })
    control_audit = []
    for env, source in zip(controls, base_audit["controls"]):
        item = items[env["item_index"]]
        assert exact_formula(env["derivation"]) == env["true_answer"]
        assert env["derivation"] == source["formula"]
        assert not module.precheck_rewrite(env["class"], item["prompt"], item["answer"], env["prompt"], env["answer"])
        rulings = [driver.contract._referee(f, env["class"], item["prompt"], item["answer"], env["prompt"], env["answer"]) for f in (1, 2)]
        assert rulings == ["INADMISSIBLE", "INADMISSIBLE"]
        control_audit.append({"item_index": env["item_index"], "class": env["class"],
                              "formula": env["derivation"], "computed_answer": env["true_answer"],
                              "supplied_answer": env["answer"], "scripted_referee_framings": rulings,
                              "source_reason": source["reason"]})

    # Exact old and new request maps prevent treating changed prompts as an
    # exact-prompt replay. Old response objects are never altered.
    def requests_for(old_items, old_rewrites):
        result = {}
        params = claim["decode_params"]
        for index, item in enumerate(old_items):
            for mode, prompt in (("PINNED", item["prompt"]), ("REWRITE", old_rewrites[index]["prompt"])):
                result[index, mode] = json.loads(module._chat_body(MODEL, claim["prompt_template"]["system"],
                    claim["prompt_template"]["user"].replace("{{item}}", prompt), params, 0))
            prefix, _ = module.split_for_recall(item["prompt"], 400)
            result[index, "RECALL"] = json.loads(module._chat_body(MODEL, "", module.RECALL_INSTRUCTION + prefix, params, module.RECALL_MAX_TOKENS))
        return result

    old_requests, new_requests = requests_for(base_items, base_rewrites), requests_for(items, rewrites)
    transcript_path = "runs/v2-llama-requests.jsonl"
    raw_transcript = (ROOT / transcript_path).read_bytes()
    originals[transcript_path] = raw_transcript
    raw_rows = [json.loads(line) for line in raw_transcript.decode().splitlines() if line.strip()]
    recorded = {}
    for index, row in enumerate(raw_rows):
        request = deepcopy(row["request"])
        assert request.pop("provider") == PROVIDER
        key = canonical(request)
        assert key not in recorded
        recorded[key] = (index, row["response"])
    assert len(recorded) == 72 == len(new_requests)
    assert set(recorded) == {canonical(r) for r in old_requests.values()}
    lookup, replay_audit = {}, []
    for identity, new_request in new_requests.items():
        index, mode = identity
        old_request = old_requests[identity]
        assert new_request != old_request
        prompt = items[index]["prompt"] if mode != "REWRITE" else rewrites[index]["prompt"]
        assert prompt == PREFIX + (base_items[index]["prompt"] if mode != "REWRITE" else base_rewrites[index]["prompt"])
        if mode == "RECALL":
            assert new_request["messages"][-1]["content"] == module.RECALL_INSTRUCTION + module.split_for_recall(prompt, 400)[0]
        else:
            assert new_request["messages"][-1]["content"] == claim["prompt_template"]["user"].replace("{{item}}", prompt)
        line, response = recorded[canonical(old_request)]
        key = canonical(new_request)
        assert key not in lookup
        lookup[key] = response
        replay_audit.append({"item_index": index, "mode": mode, "source_line_1based": line + 1,
                             "old_request_sha256": sha(canonical(old_request).encode()),
                             "new_request_sha256": sha(key.encode()),
                             "unmodified_response_sha256": sha(canonical(response).encode()),
                             "exact_new_request_and_prefix_checked": True})
    seen, errors = set(), []

    def replay_http(url, body):
        key = canonical(json.loads(body))
        if url != claim["endpoint"] or key not in lookup or key in seen:
            errors.append("unexpected or duplicate request")
            raise AssertionError(errors[-1])
        seen.add(key)
        return 200, canonical(lookup[key]).encode()

    world.http = replay_http
    driver.gl.nondet.web.handler = replay_http
    # Exercise actual spent-content guards against a seeded prior-corpus fixture.
    for old_hash in prior_commitments | prior_content:
        driver.contract.spent[old_hash] = 1
    bond, stake = int(claim["bond"]), int(claim["stake"])
    cid = driver.call(driver.addr(1), "open_claim", claim["subject"], claim["endpoint"], 1000,
        json.dumps(scenarios.hashes_of(items)), claim["scoring_rule"], json.dumps(claim["prompt_template"]),
        json.dumps(claim["decode_params"]), ",".join(claim["classes"]), claim["delta_threshold"],
        claim["recall_threshold"], claim["min_items"], bond, stake, json.dumps(claim["extras"]), value=bond)
    hid = driver.call(driver.addr(2), "challenge", cid, json.dumps(list(range(24))), json.dumps(claim["classes"]), value=stake * 24)
    scenarios.reveal(driver, cid, items=items)
    scenarios.run_trial(driver, hid, subset=list(range(24)), envelopes=rewrites)
    probes = scenarios.probes_of(driver, hid)
    assert not errors and len(seen) == 72
    assert all(p["pinned"] == p["rewrite"] == "RIGHT" and p["recall"] == "MISS" and
               p["stage_c1"] == p["stage_c2"] == "ADMISSIBLE" for p in probes)
    local_verdict = driver.call(driver.addr(3), "rule", hid)
    cert = driver.view("certificate", cid)
    assert local_verdict == "CLEAN" and not driver.broken
    assert world.judge_calls == 0, "numeric scoring used a scripted LLM marker"
    assert driver.view("get_claim", cid)["trial_window_s"] == 21600
    assert all((ROOT / path).read_bytes() == raw for path, raw in originals.items())

    all_prompts = [i["prompt"] for i in items] + [e["prompt"] for e in rewrites.values()]
    audit = {
        "format": "impeach-synthetic-audit/1", "dataset": DATASET, "seed": SEED,
        "status": "DRAFT_PREPARATION_NO_NEW_MODEL_OR_NATIVE_RESULT",
        "scope": "Offline arithmetic, collision, contract-gate and cross-prompt old-response regression checks only.",
        "disclosure": DISCLOSURE,
        "draft_note": "Prepared as a separate candidate claim while final auditing of the prior native case remains separate. This audit does not declare the prior case complete or diagnose its storage issue. The requested 1000-per-mille oath has not been measured on these new prefixed prompts.",
        "construction": dict(items_doc["construction"], generator="scripts/generate_court24_v3.py",
                             generator_sha256=sha(Path(__file__).read_bytes()),
                             prefix_applied="Exactly once to all 24 originals, 24 rewrites and 4 controls."),
        "frozen_terms": {"endpoint": claim["endpoint"], "model": MODEL, "provider": PROVIDER,
                         "score_milli": 1000, "trial_window_s": 21600, "reveal_window_s": 3600,
                         "decode_params": claim["decode_params"], "other_terms_unchanged_from_v2": True},
        "summary": {"items": 24, "honest_rewrites": 24, "controls": 4,
                    "class_counts": dict(Counter(e["class"] for e in rewrites.values())),
                    "original_and_rewrite_formulas_correct": 48,
                    "answer_preserving_rewrites": 19, "numeral_substitutions_change_answer": 5,
                    "honest_contract_precheck_passes": 24, "honest_cli_envelope_lint_passes": 24,
                    "unique_item_commitments": 24, "unique_original_content_hashes": 24,
                    "unique_rewrite_content_hashes": 24, "unique_salts": 24,
                    "colliding_commitments_with_all_prior_claims": 0,
                    "colliding_original_rewrite_control_content_with_all_prior_claims": 0,
                    "reused_prior_salts": 0, "prior_claims_checked": len(prior_claims),
                    "original_and_rewrite_recall_eligible": 48,
                    "unique_recall_prefixes_at_400": len({module.split_for_recall(i["prompt"], 400)[0] for i in items}),
                    "max_prompt_chars": max(map(len, all_prompts + [e["prompt"] for e in controls])),
                    "max_item_chars_allowed": module.MAX_ITEM_CHARS,
                    "minimum_squashed_tail_chars": min(len(module.squash(module.split_for_recall(p, 400)[1])) for p in all_prompts),
                    "source_files_unchanged": True, "new_model_calls": 0, "chain_calls": 0},
        "comparison": {"claims": prior_claims, "prior_item_commitments": len(prior_commitments),
                       "prior_prompt_content_hashes": len(prior_content),
                       "files": [{"path": p, "sha256": sha(raw)} for p, raw in sorted(originals.items())]},
        "contract_harness": {"runtime": "test/drivers.py StubDriver, real contracts/impeach.py on local stub",
                             "contract_sha256": sha((ROOT / "contracts/impeach.py").read_bytes()),
                             "build_sha256": sha((ROOT / "build/impeach.py").read_bytes()),
                             "operations": "seed prior spent hashes, open exact claim, challenge all24, reveal24, 96 local probe calls, local rule; no chain operations",
                             "referee": "Scripted arithmetic and declared-class fixtures; not a real model referee or validator consensus.",
                             "honest_both_framings_admitted": 24, "controls_both_framings_rejected": 4,
                             "numeric_llm_marker_calls": 0, "solvency_violations": 0},
        "old_response_regression_replay": {
            "kind": "CROSS_PROMPT_OFFLINE_REGRESSION_ONLY", "source": transcript_path,
            "source_sha256": sha(raw_transcript), "source_calls": 72, "replayed_responses": 72,
            "new_prompt_model_measurements": 0, "exact_prompt_replay": False,
            "limitation": "The old v2 raw response objects are mapped by item/mode to exact newly generated requests, including recomputed recall prefixes. This checks numeric scoring and local state-machine plumbing only; it does not establish that the model will answer or recall the new prefixed text the same way. Admission is scripted.",
            "local_fixture_result": {"verdict": local_verdict, **{k: cert[k] for k in (
                "pinned_milli", "rewrite_milli", "delta_milli", "recall_milli", "admissible_probes", "stale_answers")}},
            "mapping": replay_audit},
        "items": item_audit, "controls": control_audit,
        "artifact_sha256": [{"path": p, "sha256": sha(raw)} for p, raw in sorted(outputs.items())],
    }
    assert audit["summary"]["unique_recall_prefixes_at_400"] == 24
    outputs["calibration/court24-v3-audit.json"] = packed(audit)
    return outputs, audit


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate without writing")
    args = parser.parse_args()
    with patch.object(socket, "create_connection", side_effect=AssertionError("network forbidden")), \
         patch.object(socket.socket, "connect", side_effect=AssertionError("network forbidden")):
        outputs, audit = generate()
    for path, raw in outputs.items():
        dest = ROOT / path
        if args.check:
            assert dest.exists() and dest.read_bytes() == raw, "generated bytes differ: " + path
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(raw)
    print(json.dumps({"mode": "checked" if args.check else "generated", "files": len(outputs),
                      "summary": audit["summary"], "offline_replay": audit["old_response_regression_replay"]["local_fixture_result"]}, indent=2))


if __name__ == "__main__":
    main()
